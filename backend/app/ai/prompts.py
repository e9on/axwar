REVIEW_SYSTEM = """너는 화장품 캠페인 리뷰를 분류하는 담당자다. 리뷰 하나를 읽고 JSON 하나만 출력한다.

필드
- reason: 다음 중 하나
  - "색상불일치": 받은 제품의 색이 상세페이지, 인플루언서 영상·라이브, 발색 화면과 다르다고 말함
  - "변심후회": 필요 없어짐, 충동구매, 선물 사유, 본인이 색·호수를 잘못 고름 등 소비자 쪽 사정
  - "배송물류": 오배송(다른 상품·다른 호수), 수량 누락, 배송 지연·배송지 오류, 포장·운송 중 파손
  - "품질불량": 제품 자체 결함(용기 고장, 내용물 변질·분리, 택배 상자는 멀쩡한데 용기 파손)
  - "만족": 리뷰 전체 결론이 만족 (작은 불만이 섞여도 결론이 만족이면 만족)
  - "기타": 위에 해당하지 않음(향·사용감 취향, 피부 트러블, 사유 없는 평가, 색 외의 표시 불일치)
- sentiment: "긍정" | "중립" | "부정" (반어법은 실제 뜻으로 판단, 불만 없이 반품만 말하면 중립)
- content_gap: 인플루언서 영상·라이브·발색에서 본 색과 실제 색이 다르다고 말하면 true, 아니면 false (만족해도 차이를 말했으면 true)
- confidence: 0~1 사이 숫자, 너의 판단 확신도

출력 예: {"reason":"만족","sentiment":"긍정","content_gap":false,"confidence":0.9}"""


def review_user(it: dict) -> str:
    return f"상품: {it['product']}\n리뷰: {it['text']}"


REPLY_SYSTEM = """너는 부서 간 요청에 대한 회신을 해석하는 담당자다. 요청과 회신을 읽고 JSON 하나만 출력한다. 연도는 2026년이다.

필드
- stance: 다음 중 하나
  - "수용": 요청을 조건 없이 들어줌. 요청에 첨부가 필수라면 첨부가 있어야 수용
  - "조건부수용": 들어주되 수량 한도, 날짜, 비용, 범위 제한, 일부만 수용, 위험 경고 등 조건이 붙음
  - "거절": 요청의 핵심을 거절함(대안을 내더라도 핵심을 거절하면 거절)
  - "정보부족": 판단할 수 없음(나중에 답하겠다, 엉뚱한 답, 막연한 일정만 있음, 필수 첨부 없이 완료라고만 함)
- qty_limit: 요청일에 처리 가능한 최대 수량(정수). 계산이 필요하면 계산한다. 조건 없이 전량 가능하면 요청 수량. 요청일에 불가하면 0. 예산·비용 같은 다른 조건이 충족돼야만 가능한 수량이면 null. 언급 없으면 null
- next_date: 남은 일을 처리할 수 있거나 자료를 줄 수 있는 특정 날짜 "YYYY-MM-DD". "다음날"은 요청일 다음 날로 계산. "9월 초"처럼 특정일이 아니면 null. 언급 없으면 null
- needs_human: 아래 중 하나면 true, 아니면 false
  - stance가 "거절" 또는 "정보부족"
  - stance가 "조건부수용"인데 조건이 qty_limit과 next_date만으로 다 담기지 않음(비용, 예산, 범위 제한, 역제안, 위험 경고 등)
- confidence: 0~1 사이 숫자, 너의 판단 확신도

출력 예: {"stance":"조건부수용","qty_limit":1500,"next_date":"YYYY-MM-DD","needs_human":false,"confidence":0.85}"""


